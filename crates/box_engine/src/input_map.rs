//! Translation from winit events to `box_core::input`.

use box_core::input::{KeyCode, MouseButton};
use winit::event::MouseButton as WButton;
use winit::keyboard::KeyCode as W;

pub fn key(code: W) -> Option<KeyCode> {
    use KeyCode as K;
    Some(match code {
        W::KeyA => K::A,
        W::KeyB => K::B,
        W::KeyC => K::C,
        W::KeyD => K::D,
        W::KeyE => K::E,
        W::KeyF => K::F,
        W::KeyG => K::G,
        W::KeyH => K::H,
        W::KeyI => K::I,
        W::KeyJ => K::J,
        W::KeyK => K::K,
        W::KeyL => K::L,
        W::KeyM => K::M,
        W::KeyN => K::N,
        W::KeyO => K::O,
        W::KeyP => K::P,
        W::KeyQ => K::Q,
        W::KeyR => K::R,
        W::KeyS => K::S,
        W::KeyT => K::T,
        W::KeyU => K::U,
        W::KeyV => K::V,
        W::KeyW => K::W,
        W::KeyX => K::X,
        W::KeyY => K::Y,
        W::KeyZ => K::Z,
        W::Digit0 => K::Digit0,
        W::Digit1 => K::Digit1,
        W::Digit2 => K::Digit2,
        W::Digit3 => K::Digit3,
        W::Digit4 => K::Digit4,
        W::Digit5 => K::Digit5,
        W::Digit6 => K::Digit6,
        W::Digit7 => K::Digit7,
        W::Digit8 => K::Digit8,
        W::Digit9 => K::Digit9,
        W::Space => K::Space,
        W::Enter => K::Enter,
        W::Escape => K::Escape,
        W::Tab => K::Tab,
        W::Backspace => K::Backspace,
        W::Delete => K::Delete,
        W::ArrowLeft => K::Left,
        W::ArrowRight => K::Right,
        W::ArrowUp => K::Up,
        W::ArrowDown => K::Down,
        W::ShiftLeft => K::ShiftLeft,
        W::ShiftRight => K::ShiftRight,
        W::ControlLeft => K::ControlLeft,
        W::ControlRight => K::ControlRight,
        W::AltLeft => K::AltLeft,
        W::AltRight => K::AltRight,
        W::SuperLeft => K::SuperLeft,
        W::SuperRight => K::SuperRight,
        W::F1 => K::F1,
        W::F2 => K::F2,
        W::F3 => K::F3,
        W::F4 => K::F4,
        W::F5 => K::F5,
        W::F6 => K::F6,
        W::F7 => K::F7,
        W::F8 => K::F8,
        W::F9 => K::F9,
        W::F10 => K::F10,
        W::F11 => K::F11,
        W::F12 => K::F12,
        _ => return None,
    })
}

pub fn button(b: WButton) -> MouseButton {
    match b {
        WButton::Left => MouseButton::Left,
        WButton::Right => MouseButton::Right,
        WButton::Middle => MouseButton::Middle,
        WButton::Back => MouseButton::Other(3),
        WButton::Forward => MouseButton::Other(4),
        WButton::Other(n) => MouseButton::Other(n),
    }
}
