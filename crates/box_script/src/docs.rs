/// The first sentence of a description, on one line, for tables.
fn summary(doc: &str) -> String {
    let para = doc.split("\n\n").next().unwrap_or(doc);
    let line: Vec<&str> = para.split_whitespace().collect();
    let line = line.join(" ");
    let cut = line
        .match_indices(". ")
        .map(|(i, _)| i + 1)
        .find(|&i| !line[..i].ends_with("e.g.") && !line[..i].ends_with("i.e."))
        .unwrap_or(line.len());
    line[..cut].replace('|', "\\|")
}

/// GitHub's heading anchors: lower case, punctuation dropped, spaces as
/// dashes, `-1`, `-2` for repeats.
struct Anchors(HashMap<String, usize>);

impl Anchors {
    fn new() -> Self {
        Self(HashMap::new())
    }

    fn slug(&mut self, heading: &str) -> String {
        let base: String = heading
            .to_lowercase()
            .chars()
            .filter_map(|c| match c {
                c if c.is_alphanumeric() || c == '-' || c == '_' => Some(c),
                ' ' => Some('-'),
                _ => None,
            })
            .collect();
        let n = self.0.entry(base.clone()).or_insert(0);
        let slug = if *n == 0 { base } else { format!("{base}-{n}") };
        *n += 1;
        slug
    }
}

/// Index rows: (item path, anchor, summary).
type Rows = Vec<(String, String, String)>;

fn render_api(page: &ApiPage) -> (String, Rows) {
    let mut out = format!("{GENERATED_MARKER}\n\n# {}\n\n", page.title);
    out.push_str(&page.overview);
    out.push_str("\n\n");
    let mut anchors = Anchors::new();
    anchors.slug(&page.title);
    let mut body = String::new();
    let mut rows = Vec::new();
    for item in &page.items {
        let heading = format!("`{}`", item.path);
        let anchor = anchors.slug(&heading);
        rows.push((item.path.clone(), anchor, summary(&item.doc)));
        body.push_str(&format!("## {heading}\n\n"));
        if !matches!(item.kind, Kind::Global | Kind::Class) {
            body.push_str(&format!("```luau\n{}\n```\n\n", item.signature));
        }
        body.push_str(&item.doc);
        body.push_str("\n\n");
        // Overloads (`Quat:__mul`) share one heading.
        let mut i = 0;
        while i < item.members.len() {
            let m = &item.members[i];
            let mut same = vec![m];
            while i + same.len() < item.members.len() && item.members[i + same.len()].path == m.path
            {
                same.push(&item.members[i + same.len()]);
            }
            i += same.len();
            let heading = format!("`{}`", m.path);
            let anchor = anchors.slug(&heading);
            rows.push((m.path.clone(), anchor, summary(&m.doc)));
            body.push_str(&format!("### {heading}\n\n```luau\n"));
            for s in &same {
                body.push_str(&s.signature);
                body.push('\n');
            }
            body.push_str("```\n\n");
            let mut docs: Vec<&str> = Vec::new();
            for s in &same {
                if !docs.contains(&s.doc.as_str()) {
                    docs.push(&s.doc);
                }
            }
            body.push_str(&docs.join("\n\n"));
            body.push_str("\n\n");
        }
    }
    out.push_str("| Item | Description |\n|---|---|\n");
    for (path, anchor, text) in &rows {
        out.push_str(&format!("| [`{path}`](#{anchor}) | {text} |\n"));
    }
    out.push('\n');
    out.push_str(&body);
    (out.trim_end().to_owned() + "\n", rows)
}

fn render_types(
    registry: &Registry,
    list: &[RegisteredType],
    kind: TypeKind,
    title: &str,
    intro: &str,
    missing: &mut Vec<String>,
    count: &mut usize,
) -> (String, Rows) {
    let mut out = format!("{GENERATED_MARKER}\n\n# {title}\n\n{intro}\n\n");
    let mut anchors = Anchors::new();
    anchors.slug(title);
    let mut rows = Vec::new();
    let mut body = String::new();
    let what = match kind {
        TypeKind::Component => "component",
        TypeKind::Resource => "resource",
        TypeKind::Event => "event",
    };
    for t in list {
        *count += 1;
        let doc = t.doc.map(clean_rustdoc).unwrap_or_default();
        let doc = doc.as_str();
        if doc.is_empty() {
            missing.push(format!("{what} {}", t.name));
        }
        let heading = format!("`{}`", t.name);
        let anchor = anchors.slug(&heading);
        rows.push((t.name.to_owned(), anchor, summary(doc)));
        body.push_str(&format!("## {heading}\n\n{doc}\n\n"));
        let usage = match kind {
            TypeKind::Component => format!(
                "Scripts: `e:get(\"{n}\")`, `e:set(\"{n}\", {{ ... }})`, `e:add(\"{n}\")`, `world.query(\"{n}\")`.",
                n = t.name
            ),
            TypeKind::Resource => format!(
                "Scripts: `world.resource(\"{n}\")`, `world.set_resource(\"{n}\", {{ ... }})`.",
                n = t.name
            ),
            TypeKind::Event => format!(
                "Scripts: `events.send(\"{n}\", {{ ... }})`, `events.on(\"{n}\", function(event) ... end)`.",
                n = t.name
            ),
        };
        body.push_str(&usage);
        if t.hidden {
            body.push_str(" Not offered in the editor's Add menu.");
        }
        if matches!(t.shape, Shape::Schema(_)) {
            body.push_str(" Defined by the game's native code (`.box/registry.json`).");
        }
        body.push_str("\n\n");
        let default = default_json(registry, t);
        let fields = type_fields(registry, t, default.as_ref());
        if fields.is_empty() {
            body.push_str(&format!(
                "```luau\ntype {} = {}\n```\n\n",
                t.name,
                luau_of(registry, t)
            ));
            continue;
        }
        for f in &fields {
            *count += 1;
            let doc = f.doc.as_deref().map(clean_rustdoc).unwrap_or_default();
            let doc = doc.as_str();
            if doc.is_empty() {
                missing.push(format!("{what} {}.{}", t.name, f.name));
            }
            let mut line = format!("- **`{}`** `{}`", f.name, f.luau.replace('`', ""));
            let mut facts = Vec::new();
            if let Some(d) = &f.default {
                let text = d.to_string();
                if text.len() <= 60 {
                    facts.push(format!("default `{text}`"));
                }
            }
            if let Some((min, max)) = f.range {
                facts.push(format!("range {}–{}", num(min), num(max)));
            }
            if let Some(u) = &f.unit {
                facts.push(format!("unit {u}"));
            }
            if f.hidden {
                facts.push("hidden in the inspector".into());
            }
            if !facts.is_empty() {
                line.push_str(&format!(" ({})", facts.join(", ")));
            }
            line.push_str(&format!(": {}\n", one_line(doc)));
            body.push_str(&line);
        }
        body.push('\n');
    }
    out.push_str(&format!(
        "| {} | Description |\n|---|---|\n",
        capitalise(what)
    ));
    for (name, anchor, text) in &rows {
        out.push_str(&format!("| [`{name}`](#{anchor}) | {text} |\n"));
    }
    out.push('\n');
    out.push_str(&body);
    (out.trim_end().to_owned() + "\n", rows)
}

fn one_line(s: &str) -> String {
    s.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn num(v: f64) -> String {
    if v.is_infinite() {
        if v > 0.0 {
            "∞".into()
        } else {
            "−∞".into()
        }
    } else {
        format!("{v}")
    }
}

fn capitalise(s: &str) -> String {
    let mut c = s.chars();
    c.next()
        .map(|f| f.to_uppercase().collect::<String>() + c.as_str())
        .unwrap_or_default()
}

fn render_index(pages: &[(String, String, Rows)], count: usize) -> Page {
    let mut out = format!("{GENERATED_MARKER}\n\n# Script API reference\n\n{INDEX_OVERVIEW}\n\n");
    out.push_str(&format!(
        "{count} items. Regenerate with `box script docs --out docs/reference` (engine) or `box script docs --project <dir>` (a project's own types).\n\n## Pages\n\n"
    ));
    for (file, title, rows) in pages {
        out.push_str(&format!("- [{title}]({file}) ({} items)\n", rows.len()));
    }
    out.push_str("\n## Globals and types\n\n| Name | Page | Description |\n|---|---|---|\n");
    for (file, title, rows) in pages {
        // Top-level names only: a member path has a `.` or `:`, except
        // on the type pages, whose rows are all top level.
        let types_page = matches!(
            file.as_str(),
            "components.md" | "resources.md" | "event-types.md"
        );
        if types_page {
            continue;
        }
        for (path, anchor, text) in rows {
            if path.contains(['.', ':']) {
                continue;
            }
            out.push_str(&format!(
                "| [`{path}`]({file}#{anchor}) | {title} | {text} |\n"
            ));
        }
    }
    Page {
        path: "README.md".into(),
        text: out.trim_end().to_owned() + "\n",
    }
}

