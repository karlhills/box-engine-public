/// One field of a registered type, for the reference.
struct FieldDoc {
    name: String,
    luau: String,
    doc: Option<String>,
    default: Option<Json>,
    range: Option<(f64, f64)>,
    unit: Option<String>,
    hidden: bool,
}

fn type_fields(registry: &Registry, t: &RegisteredType, default: Option<&Json>) -> Vec<FieldDoc> {
    let field_default = |name: &str| default.and_then(|d| d.get(name)).cloned();
    match &t.shape {
        Shape::Info(info) => {
            let TypeInfo::Struct(s) = info else {
                return Vec::new();
            };
            let metas: Vec<FieldMeta> = match t.kind {
                TypeKind::Component => registry.component(t.name).map(|c| c.fields()),
                TypeKind::Resource => registry.resource(t.name).map(|r| r.fields()),
                TypeKind::Event => registry.event(t.name).map(|e| e.fields()),
            }
            .unwrap_or_default();
            s.iter()
                .zip(metas)
                .map(|(f, m)| FieldDoc {
                    name: f.name().to_owned(),
                    luau: field_type(f.type_info(), 0),
                    doc: m.doc.map(str::to_owned),
                    default: field_default(f.name()),
                    range: m.range.map(|r| (r.min, r.max)),
                    unit: m.unit.map(str::to_owned),
                    hidden: m.hidden,
                })
                .collect()
        }
        Shape::Schema(entry) => entry["fields"]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(|f| {
                let name = f["name"].as_str()?.to_owned();
                Some(FieldDoc {
                    luau: schema_field_type(registry, f["type_path"].as_str()),
                    doc: f["doc"].as_str().map(str::to_owned),
                    default: field_default(&name),
                    range: f["range"]["min"].as_f64().zip(f["range"]["max"].as_f64()),
                    unit: f["unit"].as_str().map(str::to_owned),
                    hidden: f["hidden"].as_bool().unwrap_or(false),
                    name,
                })
            })
            .collect(),
    }
}

fn default_json(registry: &Registry, t: &RegisteredType) -> Option<Json> {
    let value = match (&t.shape, t.kind) {
        (Shape::Schema(entry), _) => return Some(entry["default"].clone()),
        (_, TypeKind::Component) => registry.component(t.name)?.default_value(),
        (_, TypeKind::Resource) => registry.resource(t.name)?.default_value(),
        (_, TypeKind::Event) => registry.event(t.name)?.default_value(),
    }?;
    registry
        .value_to_json(value.as_ref() as &dyn PartialReflect)
        .ok()
}

/// The Luau type the definitions file gives a registered type.
fn luau_of(registry: &Registry, t: &RegisteredType) -> String {
    match &t.shape {
        Shape::Info(info) => luau_type(info, 0, false),
        Shape::Schema(entry) => schema_type(registry, entry, false),
    }
}

// ----- the reference -----

/// One generated Markdown page.
#[derive(Clone, Debug)]
pub struct Page {
    /// Path relative to the output folder (`world.md`).
    pub path: String,
    pub text: String,
}

/// The generated reference: pages and what lacks a description.
pub struct Reference {
    pub pages: Vec<Page>,
    undocumented: Vec<String>,
    items: usize,
}

impl Reference {
    /// Items without a description (`world.spawn (world)`); empty when
    /// every item is documented.
    pub fn undocumented(&self) -> &[String] {
        &self.undocumented
    }

    /// How many items the reference describes (globals, functions,
    /// methods, fields, types, registered types and their fields).
    pub fn item_count(&self) -> usize {
        self.items
    }

    /// Writes the pages into `dir` (created if missing), skipping files
    /// whose content is unchanged, and removes generated pages (those
    /// starting with [`GENERATED_MARKER`]) that are no longer produced.
    /// Returns how many files were written.
    pub fn write(&self, dir: &Path) -> std::io::Result<usize> {
        std::fs::create_dir_all(dir)?;
        let mut written = 0;
        for page in &self.pages {
            let path = dir.join(&page.path);
            if std::fs::read_to_string(&path).is_ok_and(|old| old == page.text) {
                continue;
            }
            std::fs::write(&path, &page.text)?;
            written += 1;
        }
        for entry in std::fs::read_dir(dir)?.flatten() {
            let path = entry.path();
            let name = entry.file_name().to_string_lossy().into_owned();
            if path.extension().is_some_and(|e| e == "md")
                && !self.pages.iter().any(|p| p.path == name)
                && std::fs::read_to_string(&path).is_ok_and(|t| t.starts_with(GENERATED_MARKER))
            {
                std::fs::remove_file(&path)?;
            }
        }
        Ok(written)
    }
}

/// An API's definitions as the reference reads them: placeholders become
/// the generic declarations (the typed overloads per component, resource
/// and event are listed on the type pages instead).
fn api_text(api: &dyn ScriptApi, apis: &[Arc<dyn ScriptApi>]) -> String {
    let methods = format!("{}{GENERIC_ACCESSORS}", entity_extra_methods(apis));
    api.definitions()
        .replace("@COMPONENT_METHODS@", &methods)
        .replace("@RESOURCE_GET@", "(name: string) -> any")
        .replace("@EVENT_SEND@", "(name: string, payload: any?) -> ()")
}

/// What one page of the reference holds before rendering.
struct ApiPage {
    file: String,
    title: String,
    overview: String,
    items: Vec<Item>,
}

/// The reference for `registry` and the built-in APIs plus `extra` (the
/// same inputs as [`crate::types::definitions`]).
pub fn reference(registry: &Registry, extra: &[Arc<dyn ScriptApi>]) -> Reference {
    let mut apis = builtin_apis();
    apis.extend(extra.iter().cloned());
    let mut undocumented = Vec::new();
    let mut count = 0;

    let mut api_pages: Vec<ApiPage> = Vec::new();
    for api in &apis {
        let text = api_text(api.as_ref(), &apis);
        let items = parse(&text);
        if items.is_empty() {
            continue;
        }
        let overview = api.doc().trim().to_owned();
        if overview.is_empty() {
            undocumented.push(format!(
                "the `{}` API has no overview (ScriptApi::doc)",
                api.name()
            ));
        }
        api_pages.push(ApiPage {
            file: format!("{}.md", api.name().to_lowercase()),
            title: format!("`{}`", api.name()),
            overview,
            items,
        });
    }
    api_pages.push(ApiPage {
        file: "script-modules.md".into(),
        title: "Script modules".into(),
        overview: SCRIPT_MODULES_OVERVIEW.into(),
        items: parse(SCRIPT_MODULE),
    });
    let types = RegisteredTypes::of(registry);
    let names: Vec<&str> = types.components.iter().map(|t| t.name).collect();
    api_pages.push(ApiPage {
        file: "rules.md".into(),
        title: "Script rules".into(),
        overview: RULES_OVERVIEW.into(),
        items: parse(&crate::rules::definitions(&names)),
    });
    for page in &api_pages {
        for item in &page.items {
            check(item, &page.title, &mut undocumented, &mut count);
        }
    }

    let mut pages = Vec::new();
    let mut index_rows = Vec::new();
    for page in &api_pages {
        let (text, rows) = render_api(page);
        pages.push(Page {
            path: page.file.clone(),
            text,
        });
        index_rows.push((page.file.clone(), page.title.clone(), rows));
    }
    for (kind, list, file, title, intro) in [
        (
            TypeKind::Component,
            &types.components,
            "components.md",
            "Components",
            COMPONENTS_OVERVIEW,
        ),
        (
            TypeKind::Resource,
            &types.resources,
            "resources.md",
            "Resources",
            RESOURCES_OVERVIEW,
        ),
        (
            TypeKind::Event,
            &types.events,
            "event-types.md",
            "Event types",
            EVENTS_OVERVIEW,
        ),
    ] {
        let (text, rows) = render_types(
            registry,
            list,
            kind,
            title,
            intro,
            &mut undocumented,
            &mut count,
        );
        pages.push(Page {
            path: file.into(),
            text,
        });
        index_rows.push((file.into(), title.into(), rows));
    }
    pages.insert(0, render_index(&index_rows, count));
    Reference {
        pages,
        undocumented,
        items: count,
    }
}

fn check(item: &Item, page: &str, missing: &mut Vec<String>, count: &mut usize) {
    *count += 1;
    if item.doc.trim().is_empty() {
        missing.push(format!("{} ({page})", item.path));
    }
    for m in &item.members {
        check(m, page, missing, count);
    }
}

