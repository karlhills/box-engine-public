//! The script API reference: Markdown pages for every global, function,
//! method, value type, lifecycle callback, rule type and registered
//! component, resource and event (`box script docs`).
//!
//! Generated from the same sources as the luau-lsp definitions
//! ([`crate::types`]), so the two cannot disagree:
//!
//! - Each [`ScriptApi`]'s [`definitions`](ScriptApi::definitions) text,
//!   whose `--- description` lines (the ones luau-lsp shows on hover) give
//!   each item its text, and its [`doc`](ScriptApi::doc) overview. The
//!   declarations are parsed ([`parse`]): `declare name: { field: T, ... }`
//!   tables, `declare function`, `declare extern type X with ... end`
//!   classes and `type X = ...` aliases with their fields.
//! - The script module and rule declarations ([`crate::types`],
//!   [`crate::rules::definitions`]).
//! - The registry: each component, resource and event with its doc
//!   comment, and each field's Luau type, default, range, unit and doc
//!   comment (reflection metadata, or a schema-only type's
//!   `.box/registry.json` entry).
//!
//! [`Reference::undocumented`] lists every item without a description;
//! the engine's reference test requires it to be empty.

