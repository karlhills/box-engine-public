//! [`Derived`]: the runtime marker on entities a rule generated from the
//! saved intent of an owner entity, with their stable [`PartKey`]s and the
//! [`GeneratedWarnings`] shown on the owner.
//!
//! Procedural authoring saves intent (a wall path, a room) and derives
//! everything else (docs/PROCEDURAL.md §2, docs/PROCEDURAL_DIRECTION.md §5).
//! `box_proc::derive::reconcile` spawns, updates and despawns the derived
//! entities; this module holds the data every crate needs to treat them
//! like prefab contents ([`crate::prefab::Instanced`]): scene saving skips
//! them, `box_core::edit` refuses to edit them or to place entities under
//! them, picking selects their owner ([`crate::prefab::editable_ancestor`]),
//! and the editor shows them read-only. Use
//! [`crate::prefab::is_generated`] to test for either marker.
//!
//! Derived entities are children of their owner, so their `Transform` is
//! relative to it and they are despawned with it.

use std::fmt;

use crate::identity::Uid;
use crate::world::Entity;

/// Runtime marker on every entity generated by a rule. Not registered, so
/// never saved: `scene::save` skips it, `box_core::edit` refuses to edit it
/// (edit the owner's intent instead) and the editor selects the owner when
/// it is clicked. Added by `box_proc::derive::reconcile`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Derived {
    /// The entity whose intent produced this part (also its parent).
    pub owner: Entity,
    /// Stable, semantic key: `<owner uid>/<role>`.
    pub key: PartKey,
    /// Name of the rule that produced it (`"walls"`).
    pub rule: String,
}

/// The stable key of a derived part: `<owner uid>/<role>`, such as
/// `0193…/wall`, `0193…/end0` or `0193…/wall1/cap`.
///
/// Keys must be **semantic, never positional**: they name what the part is
/// for its owner (`wall`, `end0` for the path's first end, `room2/wall1` for
/// a room's side 1), so they do not change when a neighbour is added or
/// removed. The derived entity's uid is computed from the key
/// ([`PartKey::uid`]), so selection by uid and (from M6) per-part overrides
/// stay valid across regenerations, undo, save and reload. A key is unique
/// per owner across all rules.
///
/// ```
/// use box_core::derived::PartKey;
/// use box_core::identity::Uid;
///
/// let owner = Uid::from_u128(7);
/// let key = PartKey::new(owner, "wall");
/// assert_eq!(key.role(), "wall");
/// assert_eq!(key.owner(), Some(owner));
/// assert_eq!(key.child("cap").role(), "wall/cap");
/// assert_eq!(key.uid(), PartKey::new(owner, "wall").uid());
/// assert!(key.check(owner).is_ok());
/// assert!(PartKey::new(owner, "3").check(owner).is_err()); // positional
/// ```
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct PartKey(String);

impl PartKey {
    /// `<owner>/<role>`. `role` may have several `/`-separated segments.
    pub fn new(owner: Uid, role: impl AsRef<str>) -> Self {
        Self(format!("{owner}/{}", role.as_ref()))
    }

    /// A key below this one: `<self>/<role>`.
    pub fn child(&self, role: impl AsRef<str>) -> Self {
        Self(format!("{}/{}", self.0, role.as_ref()))
    }

    /// A key from its text, as [`PartKey::as_str`] gives it.
    pub fn from_string(key: impl Into<String>) -> Self {
        Self(key.into())
    }

    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The owner uid the key starts with (`None` if it does not start with
    /// one).
    pub fn owner(&self) -> Option<Uid> {
        Uid::parse(self.0.split_once('/').map_or(&self.0, |(o, _)| o))
    }

    /// The part of the key after the owner uid (`wall`, `room2/wall1`).
    pub fn role(&self) -> &str {
        self.0.split_once('/').map_or("", |(_, r)| r)
    }

    /// `Ok` when the key is `<owner>/<role>` with a non-empty role made of
    /// non-empty segments, none of them a bare number (a positional index:
    /// use a semantic role such as `end0` or `wall1`). `Err` says what is
    /// wrong, for the rule's warnings.
    pub fn check(&self, owner: Uid) -> Result<(), String> {
        if self.owner() != Some(owner) {
            return Err(format!(
                "part key `{}` does not start with its owner's uid {owner}: build it with PartKey::new(owner, role)",
                self.0
            ));
        }
        let role = self.role();
        if role.is_empty() {
            return Err(format!("part key `{}` has no role", self.0));
        }
        for segment in role.split('/') {
            if segment.is_empty() || segment.trim() != segment {
                return Err(format!(
                    "part key `{}` has an empty or padded segment",
                    self.0
                ));
            }
            if segment.bytes().all(|b| b.is_ascii_digit()) {
                return Err(format!(
                    "part key `{}` uses a bare index (`{segment}`): keys must be semantic \
                     (`wall`, `end0`, `wall1/cap`) so they survive neighbours being added",
                    self.0
                ));
            }
        }
        Ok(())
    }

    /// The uid of the derived entity with this key: deterministic (the same
    /// on every run, platform, regeneration and reload) and distinct per
    /// owner and key.
    pub fn uid(&self) -> Uid {
        let owner = self.owner().unwrap_or(Uid::from_u128(0));
        crate::prefab::instanced_uid(owner, Uid::from_u128(hash128(self.0.as_bytes())))
    }
}

impl fmt::Display for PartKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Two FNV-1a passes with different bases: stable across Rust versions and
/// platforms (unlike `std::hash`), mixed further by `instanced_uid`.
fn hash128(bytes: &[u8]) -> u128 {
    const PRIME: u64 = 0x0000_0100_0000_01B3;
    let (mut a, mut b) = (0xCBF2_9CE4_8422_2325u64, 0x8422_2325_CBF2_9CE4u64);
    for &byte in bytes {
        a = (a ^ u64::from(byte)).wrapping_mul(PRIME);
        b = (b ^ u64::from(byte.rotate_left(3))).wrapping_mul(PRIME);
    }
    (u128::from(a) << 64) | u128::from(b ^ bytes.len() as u64)
}

/// One warning of a rule, shown on the owner (inspector, hierarchy badge,
/// viewport badge) and logged once when it first appears.
#[derive(Clone, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct GeneratedWarning {
    /// The rule that reported it.
    pub rule: String,
    /// The part it is about; `None` for a rule-level warning.
    pub key: Option<PartKey>,
    pub message: String,
}

impl fmt::Display for GeneratedWarning {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.key {
            Some(k) => write!(f, "{} ({}): {}", self.rule, k.role(), self.message),
            None => write!(f, "{}: {}", self.rule, self.message),
        }
    }
}

/// Runtime component on an owner: the current warnings of every rule that
/// generated parts for it, deduplicated, in a stable order. Never saved;
/// replaced per rule by each reconcile and removed when empty.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct GeneratedWarnings(pub Vec<GeneratedWarning>);

/// Runtime marker on an editor tool's preview owner (the path a drawing
/// tool is drawing): an ordinary intent entity that rules see and generate
/// parts for, so the preview is the real result, but it is generated
/// content ([`crate::prefab::is_generated`]): never saved, never edited
/// through `box_core::edit`, hidden in the hierarchy and not picked.
/// `box_proc::derive::reconcile` keeps its warnings without logging them
/// (no toasts while drawing). Never added to Play worlds (scene loads
/// cannot create it).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Preview;

/// Resource bumped whenever derived parts or [`GeneratedWarnings`] change,
/// so views (the editor's badges) rebuild their caches only then.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct GeneratedRevision(pub u64);

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_stable_semantic_and_unique() {
        let (a, b) = (Uid::from_u128(1), Uid::from_u128(2));
        let k = PartKey::new(a, "wall");
        assert_eq!(k.as_str(), format!("{a}/wall"));
        assert_eq!(k.owner(), Some(a));
        assert_eq!(k.role(), "wall");
        // Deterministic, and distinct per owner and per role.
        assert_eq!(k.uid(), PartKey::new(a, "wall").uid());
        assert_eq!(
            k.uid().to_string(),
            PartKey::from_string(k.as_str()).uid().to_string()
        );
        assert_ne!(k.uid(), PartKey::new(b, "wall").uid());
        assert_ne!(k.uid(), PartKey::new(a, "end0").uid());
        assert_ne!(k.uid(), k.child("cap").uid());
        assert_ne!(k.uid(), a);
        // A pinned value: the uid must never change between versions, or
        // overrides and selections by uid would break.
        assert_eq!(
            PartKey::new(Uid::from_u128(1), "wall").uid().to_string(),
            "e950d0b7-87a3-4aee-8c72-80b2483915e8"
        );
    }

    #[test]
    fn check_rejects_foreign_empty_and_positional_keys() {
        let (a, b) = (Uid::from_u128(1), Uid::from_u128(2));
        assert!(PartKey::new(a, "wall").check(a).is_ok());
        assert!(PartKey::new(a, "room2/wall1").check(a).is_ok());
        assert!(PartKey::new(a, "wall").check(b).is_err());
        assert!(PartKey::new(a, "").check(a).is_err());
        assert!(PartKey::new(a, "wall//cap").check(a).is_err());
        assert!(PartKey::new(a, " wall").check(a).is_err());
        let e = PartKey::new(a, "walls/12").check(a).unwrap_err();
        assert!(e.contains("bare index"), "{e}");
        assert!(PartKey::from_string("nope").check(a).is_err());
    }
}
