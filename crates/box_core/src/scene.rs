/// The scene format version this engine writes and reads.
pub const SCENE_VERSION: u32 = 1;

/// Written as entity keys, never inside `"components"`.
const HOISTED: [&str; 2] = ["Uid", "Name"];

/// The scene envelope's migration chain (step *i* upgrades `"version"`
/// *i + 1* to *i + 2*). Empty: no scene format change has needed one yet;
/// component and resource changes are type migrations
/// ([`Registry::add_migration`]).
pub fn format_chain() -> Chain {
    Chain::new(Vec::new())
}

/// Components of an entity whose types are not registered, kept as raw JSON.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct UnknownComponents(pub BTreeMap<String, Json>);

/// Top-level fields of an entity's registered components that their types
/// do not have, by component name, kept as raw JSON and written back after
/// the known fields. A field the type has gained since wins over the kept
/// copy.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct UnknownFields(pub BTreeMap<String, serde_json::Map<String, Json>>);

/// World resource: [`UnknownFields`] of the scene's registered resources.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct UnknownResourceFields(pub BTreeMap<String, serde_json::Map<String, Json>>);

/// World resource: scene resources whose types are not registered, kept as raw JSON.
#[derive(Clone, Debug, Default, PartialEq)]
pub struct UnknownResources(pub BTreeMap<String, Json>);

#[derive(Debug, thiserror::Error)]
pub enum SceneError {
    #[error("invalid JSON: {0}")]
    Json(#[from] serde_json::Error),
    #[error(
        "scene version {found} is newer than this engine supports ({supported}); update box-engine"
    )]
    NewerVersion { found: u64, supported: u32 },
    #[error("scene version {found} is not supported (this engine reads version {supported})")]
    UnsupportedVersion { found: u64, supported: u32 },
    #[error("malformed scene: {0}")]
    Format(String),
    #[error("entity {uid}, component `{component}`: {source}")]
    Component {
        uid: Uid,
        component: String,
        source: ReflectError,
    },
    #[error("resource `{resource}`: {source}")]
    Resource {
        resource: String,
        source: ReflectError,
    },
    #[error("entity {uid}, component `{component}`: {source}")]
    ComponentMigration {
        uid: Uid,
        component: String,
        source: Box<MigrateError>,
    },
    #[error(transparent)]
    Migrate(Box<MigrateError>),
    #[error(transparent)]
    Reflect(#[from] ReflectError),
}

impl From<MigrateError> for SceneError {
    fn from(e: MigrateError) -> Self {
        SceneError::Migrate(Box::new(e))
    }
}

impl SceneError {
    /// The migration error inside, if this is one.
    pub fn migration(&self) -> Option<&MigrateError> {
        match self {
            SceneError::ComponentMigration { source, .. } | SceneError::Migrate(source) => {
                Some(source)
            }
            _ => None,
        }
    }
}

// ---------------------------------------------------------------- saving ----

struct Record<'w> {
    uid: Uid,
    name: Option<Ref<'w, Name>>,
    parent: Option<Uid>,
    known: Vec<(&'static str, ComponentRef<'w>)>,
    unknown: Option<Ref<'w, UnknownComponents>>,
    extra: Option<Ref<'w, UnknownFields>>,
    registry: &'w Registry,
}

/// Serialize two name-sorted sequences as one sorted map. A name in both is
/// written once, from `known`.
fn merged_map<'a, S, K>(
    s: S,
    known: impl ExactSizeIterator<Item = (&'a str, K)>,
    unknown: Option<&'a BTreeMap<String, Json>>,
    mut write_known: impl FnMut(&mut S::SerializeMap, &'a str, K) -> Result<(), S::Error>,
) -> Result<S::Ok, S::Error>
where
    S: Serializer,
{
    // No length hint: duplicates are only found while merging.
    let mut map = s.serialize_map(None)?;
    let mut k = known.peekable();
    let mut u = unknown.into_iter().flatten().peekable();
    loop {
        let take_known = match (k.peek(), u.peek()) {
            (Some((kn, _)), Some((un, _))) => match (*kn).cmp(un.as_str()) {
                Ordering::Less => true,
                Ordering::Greater => false,
                Ordering::Equal => {
                    u.next();
                    true
                }
            },
            (Some(_), None) => true,
            (None, Some(_)) => false,
            (None, None) => break,
        };
        if take_known {
            if let Some((name, value)) = k.next() {
                write_known(&mut map, name, value)?;
            }
        } else if let Some((name, value)) = u.next() {
            map.serialize_entry(name, value)?;
        }
    }
    map.end()
}

/// Writes one registered value: streamed when it needs nothing extra,
/// otherwise through JSON to add `"$version"` (a versioned type) and the
/// kept unknown fields.
fn write_value<M: SerializeMap>(
    map: &mut M,
    registry: &Registry,
    name: &str,
    value: &dyn bevy_reflect::PartialReflect,
    extra: Option<&serde_json::Map<String, Json>>,
) -> Result<(), M::Error> {
    let types = registry.type_registry();
    let extra = extra.filter(|e| !e.is_empty());
    if extra.is_none() && registry.type_version(name) <= 1 {
        return map.serialize_entry(name, &TypedReflectSerializer::new(value, types));
    }
    let mut json = serde_json::to_value(TypedReflectSerializer::new(value, types))
        .map_err(serde::ser::Error::custom)?;
    migrate::stamp_version(registry, name, &mut json);
    if let Some(extra) = extra {
        migrate::append_fields(&mut json, extra);
    }
    map.serialize_entry(name, &json)
}

struct Components<'a, 'w>(&'a Record<'w>);

impl Serialize for Components<'_, '_> {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        let r = self.0;
        let extra = r.extra.as_deref().map(|e| &e.0);
        merged_map(
            s,
            r.known.iter().map(|(n, v)| (*n, v)),
            r.unknown.as_deref().map(|u| &u.0),
            |map, name, value| {
                write_value(
                    map,
                    r.registry,
                    name,
                    value.as_partial_reflect(),
                    extra.and_then(|e| e.get(name)),
                )
            },
        )
    }
}

impl Serialize for Record<'_> {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        let mut st = s.serialize_struct("Entity", 4)?;
        st.serialize_field("uid", &self.uid)?;
        st.serialize_field("name", &self.name.as_deref().map(Name::as_str))?;
        st.serialize_field("parent", &self.parent)?;
        st.serialize_field("components", &Components(self))?;
        st.end()
    }
}

struct Resources<'w>(&'w World);

impl Serialize for Resources<'_> {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        let world = self.0;
        let registry = world.registry();
        let known: Vec<(&str, &dyn bevy_reflect::Reflect)> = registry
            .resources()
            .filter(|r| r.is_saved())
            .filter_map(|r| Some((r.name(), (r.data.get)(world)?)))
            .collect();
        let extra = world.get_resource::<UnknownResourceFields>().map(|u| &u.0);
        merged_map(
            s,
            known.into_iter(),
            world.get_resource::<UnknownResources>().map(|u| &u.0),
            |map, name, value| {
                write_value(
                    map,
                    registry,
                    name,
                    value.as_partial_reflect(),
                    extra.and_then(|e| e.get(name)),
                )
            },
        )
    }
}

#[derive(Serialize)]
struct SceneOut<'w> {
    version: u32,
    resources: Resources<'w>,
    entities: Vec<Record<'w>>,
}

fn record<'w>(world: &'w World, registry: &'w Registry, e: Entity) -> Option<Record<'w>> {
    if is_generated(world, e) {
        return None;
    }
    let uid = world.uid(e)?;
    let known = world
        .component_names(e)
        .into_iter()
        .filter(|n| !HOISTED.contains(n))
        .filter_map(|n| {
            let ty = registry.component(n)?;
            if !ty.is_saved() {
                return None;
            }
            Some((n, (ty.data.get)(world, e)?))
        })
        .collect();
    Some(Record {
        uid,
        name: world.get::<Name>(e),
        parent: world.saved_parent(e).and_then(|p| world.uid(p)),
        known,
        unknown: world.get::<UnknownComponents>(e),
        extra: world.get::<UnknownFields>(e),
        registry,
    })
}

/// Pre-order walk of `root`'s subtree. Entities without a `Uid` have no
/// record; their descendants are still visited and record their nearest saved
/// ancestor as parent.
fn collect_subtree<'w>(
    world: &'w World,
    registry: &'w Registry,
    root: Entity,
    out: &mut Vec<Record<'w>>,
) {
    let mut stack = vec![root];
    while let Some(e) = stack.pop() {
        // Runtime-only subtrees are never saved.
        if world.has::<crate::visibility::Transient>(e) {
            continue;
        }
        out.extend(record(world, registry, e));
        stack.extend(world.children(e).into_iter().rev());
    }
}

/// Parentless entities without a `Uid` that have children, in spawn order.
/// Saved entities below them are written as roots.
fn unsaved_roots(world: &World) -> Vec<Entity> {
    type Unsaved<'a> = Without<Without<With<Entity, &'a Children>, &'a Parent>, &'a Uid>;
    let mut roots: Vec<Entity> = world.query::<Unsaved>().iter().collect();
    roots.sort_unstable_by_key(|e| e.to_bits());
    roots
}

/// Saved roots: the persisted root order, then any saved parentless entity
/// that bypassed it (raw hecs access), by uid.
fn saved_roots(world: &World) -> Vec<Entity> {
    let mut roots: Vec<Entity> = world
        .roots()
        .iter()
        .copied()
        .filter(|e| world.contains(*e) && world.parent(*e).is_none() && world.has::<Uid>(*e))
        .collect();
    let listed: HashSet<Entity> = roots.iter().copied().collect();
    let mut extra: Vec<(Uid, Entity)> = world
        .query::<Without<(Entity, &Uid), &Parent>>()
        .iter()
        .filter(|(e, _)| !listed.contains(e))
        .map(|(e, u)| (*u, e))
        .collect();
    extra.sort_unstable();
    roots.extend(extra.into_iter().map(|(_, e)| e));
    roots
}

/// Serialize the whole world (saved resources and entities) to scene JSON.
pub fn save(world: &World) -> Result<Vec<u8>, SceneError> {
    let registry = world.registry();
    let mut entities = Vec::with_capacity(world.entity_count() as usize);
    for root in saved_roots(world).into_iter().chain(unsaved_roots(world)) {
        collect_subtree(world, registry, root, &mut entities);
    }
    let scene = SceneOut {
        version: SCENE_VERSION,
        resources: Resources(world),
        entities,
    };
    Ok(to_pretty_json(&scene)?)
}

/// [`save`] as a `String`.
pub fn save_string(world: &World) -> Result<String, SceneError> {
    let bytes = save(world)?;
    String::from_utf8(bytes).map_err(|e| SceneError::Format(e.to_string()))
}

/// A subtree as entity records (root first, pre-order): the snapshot used for
/// copy/paste, duplicate and undo of spawn/despawn. Unknown components are included.
pub fn save_subtree(world: &World, root: Entity) -> Result<Vec<Json>, SceneError> {
    if world.uid(root).is_none() {
        return Err(SceneError::Format(format!(
            "entity {root:?} has no Uid and cannot be saved"
        )));
    }
    let mut records = Vec::new();
    collect_subtree(world, world.registry(), root, &mut records);
    records
        .iter()
        .map(|r| serde_json::to_value(r).map_err(SceneError::from))
        .collect()
}

/// Pretty JSON as written to scene files: two-space indent, arrays of up to
/// four numbers on one line.
pub fn to_pretty_json(value: &impl Serialize) -> Result<Vec<u8>, serde_json::Error> {
    let mut out = Vec::with_capacity(4096);
    serde_json::to_writer_pretty(&mut out, value)?;
    Ok(compact_numeric_arrays(&out))
}

/// Rewrite `[\n  1.0,\n  2.0\n]` as `[1.0, 2.0]` for arrays of 1..=4 numbers.
fn compact_numeric_arrays(src: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(src.len());
    let mut i = 0;
    let mut in_string = false;
    while i < src.len() {
        let b = src[i];
        if in_string {
            out.push(b);
            if b == b'\\' {
                if let Some(&next) = src.get(i + 1) {
                    out.push(next);
                    i += 1;
                }
            } else if b == b'"' {
                in_string = false;
            }
            i += 1;
            continue;
        }
        if b == b'"' {
            in_string = true;
        } else if b == b'['
            && let Some((items, end)) = numeric_array(src, i)
        {
            out.push(b'[');
            for (k, item) in items.iter().enumerate() {
                if k > 0 {
                    out.extend_from_slice(b", ");
                }
                out.extend_from_slice(item);
            }
            out.push(b']');
            i = end;
            continue;
        }
        out.push(b);
        i += 1;
    }
    out
}

fn numeric_array(src: &[u8], start: usize) -> Option<(Vec<&[u8]>, usize)> {
    let mut items = Vec::with_capacity(4);
    let mut j = start + 1;
    let skip_ws = |mut j: usize| {
        while src.get(j).is_some_and(u8::is_ascii_whitespace) {
            j += 1;
        }
        j
    };
    loop {
        j = skip_ws(j);
        let s = j;
        while src
            .get(j)
            .is_some_and(|c| matches!(c, b'-' | b'+' | b'.' | b'e' | b'E' | b'0'..=b'9'))
        {
            j += 1;
        }
        if s == j || items.len() == 4 {
            return None;
        }
        items.push(&src[s..j]);
        j = skip_ws(j);
        match src.get(j)? {
            b',' => j += 1,
            b']' => return Some((items, j + 1)),
            _ => return None,
        }
    }
}

// --------------------------------------------------------------- loading ----

/// Load a scene file into a new world sharing `registry`.
pub fn load(bytes: &[u8], registry: Arc<Registry>) -> Result<World, SceneError> {
    let tree: Json = serde_json::from_slice(bytes)?;
    load_value(&tree, registry)
}

/// A scene tree's `"version"`, checked: missing, 0 or newer than
/// [`SCENE_VERSION`] is an error.
pub fn tree_version(tree: &Json) -> Result<u64, SceneError> {
    let version = tree
        .get("version")
        .and_then(Json::as_u64)
        .ok_or_else(|| SceneError::Format("missing or non-numeric \"version\"".into()))?;
    if version > u64::from(SCENE_VERSION) {
        return Err(SceneError::NewerVersion {
            found: version,
            supported: SCENE_VERSION,
        });
    }
    if version == 0 {
        return Err(SceneError::UnsupportedVersion {
            found: version,
            supported: SCENE_VERSION,
        });
    }
    Ok(version)
}

/// Upgrades a scene file's envelope to [`SCENE_VERSION`] in place (the
/// [`format_chain`]); component and resource values are untouched. Needs
/// no registry, so the asset importer runs it too.
pub fn upgrade_format(tree: &mut Json, report: &mut TreeReport) -> Result<(), SceneError> {
    let version = tree_version(tree)?;
    if version == u64::from(SCENE_VERSION) {
        return Ok(());
    }
    let steps = format_chain().upgrade("scene", version as u32, tree)?;
    tree["version"] = Json::from(SCENE_VERSION);
    report.format = Some((version, SCENE_VERSION));
    report.format_steps = steps;
    Ok(())
}

/// Upgrades a whole scene tree (a `.scene.json`, a prefab, or anything with
/// `"version"`, `"resources"` and `"entities"`) to this engine and
/// `registry` in place: the envelope, type renames and every value's type
/// steps, as the file would be written now. Returns what changed (empty:
/// the file is current). Loading does the same on the fly; `box upgrade`
/// writes the result.
pub fn upgrade_tree(registry: &Registry, tree: &mut Json) -> Result<TreeReport, SceneError> {
    let mut report = TreeReport::default();
    upgrade_format(tree, &mut report)?;
    migrate::upgrade_scene_types(registry, tree, &mut report)?;
    Ok(report)
}

/// Load from the untyped value tree, upgrading an older file in memory
/// (see the module docs).
pub fn load_value(tree: &Json, registry: Arc<Registry>) -> Result<World, SceneError> {
    if tree_version(tree)? != u64::from(SCENE_VERSION) {
        let mut tree = tree.clone();
        upgrade_format(&mut tree, &mut TreeReport::default())?;
        return load_current(&tree, registry);
    }
    load_current(tree, registry)
}

fn load_current(tree: &Json, registry: Arc<Registry>) -> Result<World, SceneError> {
    let entities = tree
        .get("entities")
        .and_then(Json::as_array)
        .ok_or_else(|| SceneError::Format("missing \"entities\" array".into()))?;
    let mut world = World::with_registry(registry);
    match tree.get("resources") {
        None | Some(Json::Null) => {}
        Some(Json::Object(resources)) => load_resources(&mut world, resources)?,
        Some(_) => return Err(SceneError::Format("\"resources\" must be an object".into())),
    }
    instantiate(&mut world, entities, None)?;
    Ok(world)
}

fn load_resources(
    world: &mut World,
    resources: &serde_json::Map<String, Json>,
) -> Result<(), SceneError> {
    let registry = world.registry().clone();
    let mut unknown = BTreeMap::new();
    let mut extras = BTreeMap::new();
    for (stored, value) in resources {
        let name = registry.migrations().current_name(stored);
        if name != stored && resources.contains_key(name) {
            return Err(SceneError::Format(format!(
                "resource `{stored}` was renamed to `{name}`, and both are present"
            )));
        }
        let mut value = Cow::Borrowed(value);
        prepare_value(&registry, name, &mut value)?;
        match registry.resource(name) {
            Some(ty) => {
                let err = |source| SceneError::Resource {
                    resource: name.to_string(),
                    source,
                };
                let extra = take_unknown_fields(&registry, ty.type_id(), &mut value);
                if !extra.is_empty() {
                    warn_unknown_fields(&format!("resource `{name}`"), &extra);
                    extras.insert(name.to_string(), extra);
                }
                let v = registry
                    .value_from_json(ty.type_id(), &value)
                    .map_err(err)?;
                world
                    .insert_resource_reflect(name, v.as_ref())
                    .map_err(err)?;
            }
            None => {
                unknown.insert(name.to_string(), value.into_owned());
            }
        }
    }
    if !unknown.is_empty() {
        world.insert_resource(UnknownResources(unknown));
    }
    if !extras.is_empty() {
        world.insert_resource(UnknownResourceFields(extras));
    }
    Ok(())
}

fn parse_uid(v: Option<&Json>, what: &str) -> Result<Uid, SceneError> {
    v.and_then(Json::as_str)
        .and_then(Uid::parse)
        .ok_or_else(|| SceneError::Format(format!("bad {what} {}", v.unwrap_or(&Json::Null))))
}

/// Spawn entity records (as written by [`save`] or [`save_subtree`]).
/// Parents must precede their children. With `at`, the first record is placed
/// there instead of under its recorded parent (paste, duplicate, undo of a
/// despawn); the others keep their recorded parents. Returns the spawned
/// entities in record order. On error nothing is left spawned.
pub fn instantiate(
    world: &mut World,
    records: &[Json],
    at: Option<Placement>,
) -> Result<Vec<Entity>, SceneError> {
    let mut spawned = Vec::with_capacity(records.len());
    match instantiate_into(world, records, at, &mut spawned) {
        Ok(()) => Ok(spawned),
        Err(e) => {
            for &s in spawned.iter().rev() {
                world.despawn(s);
            }
            Err(e)
        }
    }
}

fn instantiate_into(
    world: &mut World,
    records: &[Json],
    at: Option<Placement>,
    spawned: &mut Vec<Entity>,
) -> Result<(), SceneError> {
    let registry = world.registry().clone();
    for (i, rec) in records.iter().enumerate() {
        let rec = rec
            .as_object()
            .ok_or_else(|| SceneError::Format(format!("entity record {i} is not an object")))?;
        let uid = parse_uid(rec.get("uid"), "uid")?;
        if world.entity_by_uid(uid).is_some() {
            return Err(SceneError::Reflect(ReflectError::DuplicateUid(uid)));
        }
        let e = world.spawn((uid,));
        spawned.push(e);
        match rec.get("name") {
            None | Some(Json::Null) => {}
            Some(Json::String(n)) => {
                let _ = world.insert_one(e, Name::new(n.as_str()));
            }
            Some(other) => {
                return Err(SceneError::Format(format!(
                    "entity {uid}: name must be a string or null, got {other}"
                )));
            }
        }
        let placement = match (i, at) {
            (0, Some(at)) => Some(at),
            _ => match rec.get("parent") {
                None | Some(Json::Null) => None,
                p => Some(Placement::last(Some(parse_uid(p, "parent")?))),
            },
        };
        if let Some(p) = placement {
            world.place(e, p).map_err(|err| match err {
                ReflectError::NoUid(parent) => SceneError::Format(format!(
                    "entity {uid}: parent {parent} not found (parents must precede children)"
                )),
                other => SceneError::Reflect(other),
            })?;
        }
        let components = match rec.get("components") {
            None | Some(Json::Null) => continue,
            Some(Json::Object(c)) => c,
            Some(_) => {
                return Err(SceneError::Format(format!(
                    "entity {uid}: \"components\" must be an object"
                )));
            }
        };
        let mut unknown = BTreeMap::new();
        let mut extras = BTreeMap::new();
        for (stored, value) in components {
            if HOISTED.contains(&stored.as_str()) {
                return Err(SceneError::Format(format!(
                    "entity {uid}: `{stored}` belongs in the entity record, not in \"components\""
                )));
            }
            let name = registry.migrations().current_name(stored);
            if name != stored && components.contains_key(name) {
                return Err(SceneError::Format(format!(
                    "entity {uid}: `{stored}` was renamed to `{name}`, and both are present"
                )));
            }
            let mut value = Cow::Borrowed(value);
            prepare_value(&registry, name, &mut value).map_err(|source| {
                SceneError::ComponentMigration {
                    uid,
                    component: name.to_string(),
                    source: Box::new(source),
                }
            })?;
            match registry.component(name) {
                Some(ty) => {
                    let err = |source| SceneError::Component {
                        uid,
                        component: name.to_string(),
                        source,
                    };
                    let extra = take_unknown_fields(&registry, ty.type_id(), &mut value);
                    if !extra.is_empty() {
                        warn_unknown_fields(&format!("entity {uid}, component `{name}`"), &extra);
                        extras.insert(name.to_string(), extra);
                    }
                    let v = registry
                        .value_from_json(ty.type_id(), &value)
                        .map_err(err)?;
                    world.insert_reflect(e, name, v.as_ref()).map_err(err)?;
                }
                None => {
                    unknown.insert(name.to_string(), value.into_owned());
                }
            }
        }
        if !unknown.is_empty() {
            let _ = world.insert_one(e, UnknownComponents(unknown));
        }
        if !extras.is_empty() {
            let _ = world.insert_one(e, UnknownFields(extras));
        }
    }
    Ok(())
}

/// Upgrades a stored value of type `name` to the registry's version and,
/// for a registered type, drops its `"$version"`. Clones only when the
/// value has to change.
fn prepare_value(
    registry: &Registry,
    name: &str,
    value: &mut Cow<'_, Json>,
) -> Result<(), MigrateError> {
    let versioned = value.get(migrate::VERSION_KEY).is_some() || registry.type_version(name) > 1;
    if !versioned {
        return Ok(());
    }
    let v = value.to_mut();
    migrate::upgrade_value(registry, name, v)?;
    if registry.contains(name) {
        migrate::strip_version(registry, name, v);
    }
    Ok(())
}

/// Splits off the unknown top-level fields of a struct value (cloning only
/// when there are some).
fn take_unknown_fields(
    registry: &Registry,
    type_id: std::any::TypeId,
    value: &mut Cow<'_, Json>,
) -> serde_json::Map<String, Json> {
    let Some(fields) = migrate::struct_fields(registry, type_id) else {
        return serde_json::Map::new();
    };
    let has_extra = value
        .as_object()
        .is_some_and(|o| o.keys().any(|k| !fields.contains(&k.as_str())));
    if !has_extra {
        return serde_json::Map::new();
    }
    migrate::split_unknown_fields(registry, type_id, value.to_mut())
}

fn warn_unknown_fields(what: &str, extra: &serde_json::Map<String, Json>) {
    let names: Vec<String> = extra.keys().map(|k| format!("`{k}`")).collect();
    tracing::warn!(
        target: "box_core::scene",
        "{what}: unknown field{} {} kept as written (written by a newer version of the game or engine?)",
        if names.len() == 1 { "" } else { "s" },
        names.join(", ")
    );
}

/// A component or resource type a loaded scene uses that the world's
/// registry does not know (kept verbatim; see [`UnknownComponents`]).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct UnknownType {
    /// The name in the scene file.
    pub name: String,
    /// True for a resource, false for a component.
    pub resource: bool,
    /// Entities carrying the component (0 for a resource).
    pub entities: usize,
    /// The closest registered name, when it looks like a typo.
    pub did_you_mean: Option<&'static str>,
}

impl UnknownType {
    /// A one-line warning for logs: "scene `main` uses unknown component
    /// `Coinn` on 3 entities (data kept); did you mean `Coin`? ...".
    pub fn message(&self, scene: &str) -> String {
        let what = if self.resource {
            format!("unknown resource `{}`", self.name)
        } else {
            let s = if self.entities == 1 { "y" } else { "ies" };
            format!(
                "unknown component `{}` on {} entit{s}",
                self.name, self.entities
            )
        };
        let mut message = format!("scene {scene} uses {what} (data kept)");
        match self.did_you_mean {
            Some(guess) => message.push_str(&format!("; did you mean `{guess}`?")),
            None => message.push('.'),
        }
        message.push_str(
            " If it is a game type, run the game's own player or editor \
             (a native project's `cargo run --bin player` / `--bin editor`)",
        );
        message
    }
}

/// Component and resource types in `world` (a loaded scene) that its
/// registry does not know, sorted by name, with entity counts and a
/// did-you-mean against the registered short names. Empty when everything
/// loaded. Schema-only types ([`Registry::add_schema_types`]) are known:
/// their data is raw on purpose.
pub fn unknown_types(world: &World) -> Vec<UnknownType> {
    let registry = world.registry();
    let mut counts: BTreeMap<&str, usize> = BTreeMap::new();
    let mut query = world.query::<&UnknownComponents>();
    for unknown in query.iter() {
        for name in unknown.0.keys() {
            if registry.schema(name).is_none() {
                *counts.entry(name.as_str()).or_default() += 1;
            }
        }
    }
    let guess = |name: &str| crate::reflect::did_you_mean(name, registry.names());
    let mut out: Vec<UnknownType> = counts
        .into_iter()
        .map(|(name, entities)| UnknownType {
            name: name.to_string(),
            resource: false,
            entities,
            did_you_mean: guess(name),
        })
        .collect();
    drop(query);
    if let Some(unknown) = world.get_resource::<UnknownResources>() {
        out.extend(
            unknown
                .0
                .keys()
                .filter(|n| registry.schema(n).is_none())
                .map(|name| UnknownType {
                    name: name.clone(),
                    resource: true,
                    entities: 0,
                    did_you_mean: guess(name),
                }),
        );
    }
    out
}

/// Give every record a fresh uid and rewrite references to the old uids inside
/// the records (parents and any component field holding one), so the subtree
/// can be instantiated next to the original. Returns old -> new.
pub fn remap_uids(records: &mut [Json]) -> HashMap<Uid, Uid> {
    remap_uids_with(records, |_| Uid::new())
}

/// [`remap_uids`] with the new uid of each record chosen by `new_uid(old)`
/// (prefab instances derive them deterministically).
pub fn remap_uids_with(
    records: &mut [Json],
    mut new_uid: impl FnMut(Uid) -> Uid,
) -> HashMap<Uid, Uid> {
    let mut map = HashMap::new();
    let mut by_text = HashMap::new();
    for rec in records.iter() {
        if let Some(old) = rec.get("uid").and_then(Json::as_str).and_then(Uid::parse) {
            let new = new_uid(old);
            map.insert(old, new);
            by_text.insert(old.to_string(), new.to_string());
        }
    }
    fn walk(v: &mut Json, by_text: &HashMap<String, String>) {
        match v {
            Json::String(s) => {
                if let Some(new) = by_text.get(s.as_str()) {
                    *s = new.clone();
                }
            }
            Json::Array(a) => a.iter_mut().for_each(|x| walk(x, by_text)),
            Json::Object(o) => o.values_mut().for_each(|x| walk(x, by_text)),
            _ => {}
        }
    }
    for rec in records.iter_mut() {
        walk(rec, &by_text);
    }
    map
}

/// Play-mode snapshot: a new world built only from serialized data, sharing
/// the registry. Uids are preserved, so `play.entity_by_uid(uid)` maps an edit
/// entity to its play twin.
pub fn clone_world(world: &World) -> Result<World, SceneError> {
    let bytes = save(world)?;
    load(&bytes, world.registry().clone())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compacts_short_numeric_arrays_only() {
        let v = serde_json::json!({
            "a": [1.0, -2.5e-3, 3],
            "b": [1, 2, 3, 4, 5],
            "c": ["x", 1],
            "d": [],
            "e": "[1,\n 2]",
            "f": [[1, 2], [3, 4]]
        });
        let text = String::from_utf8(to_pretty_json(&v).unwrap()).unwrap();
        assert!(text.contains("\"a\": [1.0, -0.0025, 3]"), "{text}");
        assert!(text.contains("\"b\": [\n"), "{text}");
        assert!(text.contains("\"c\": [\n"), "{text}");
        assert!(text.contains("\"d\": []"), "{text}");
        assert!(text.contains(r#""e": "[1,\n 2]""#), "{text}");
        assert!(text.contains("[1, 2],"), "{text}");
        let back: Json = serde_json::from_str(&text).unwrap();
        assert_eq!(back, v);
    }
}
