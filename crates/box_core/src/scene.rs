//! Scene files: stable-ordered JSON through the registry.
//!
//! ```json
//! {
//!   "version": 1,
//!   "resources": { "Environment": { ... } },
//!   "entities": [
//!     {
//!       "uid": "0193a4f2-...",
//!       "name": "Lamp",
//!       "parent": null,
//!       "components": {
//!         "Transform": { "translation": [0.0, 2.0, 0.0], "rotation": [0.0, 0.0, 0.0, 1.0], "scale": [1.0, 1.0, 1.0] }
//!       }
//!     }
//!   ]
//! }
//! ```
//!
//! - Entities are in hierarchy pre-order: roots in the world's persisted root
//!   order ([`World::roots`]), children in `Children` order. Loading restores
//!   both orders from the file order. An entity without a `Uid` is not
//!   saved, but its saved descendants are: they are written under their
//!   nearest saved ancestor, or as roots if there is none. Entities
//!   instantiated from a prefab ([`Instanced`](crate::prefab::Instanced)) or
//!   generated by a rule ([`Derived`](crate::derived::Derived)) count as
//!   unsaved the same way: only their `PrefabInstance` root or owner is
//!   written.
//! - `uid`, `name` and `parent` are hoisted out of `"components"`. Components
//!   and resources are sorted by name; fields follow declaration order.
//! - Entities marked `Transient` (`box_core::visibility`) and everything
//!   below them are skipped.
//! - Unregistered components and resources, and `@NotSaved` types, are skipped
//!   on save. Unregistered components and resources found in a file are kept
//!   verbatim ([`UnknownComponents`], [`UnknownResources`]) and written back
//!   byte-identically. If the type has been registered since and the entity
//!   (or world) now holds a real value, that value is written and the kept
//!   copy is dropped.
//! - Fields of a registered struct component or resource that its type does
//!   not have (a newer game version's data) are kept per component
//!   ([`UnknownFields`], [`UnknownResourceFields`]) and appended again on
//!   save, with a warning on load.
//! - Arrays of up to four numbers are written on one line (`[0.0, 1.0, 0.0]`).
//! - Loading goes through an untyped `serde_json::Value` tree. An older file
//!   is upgraded on it ([`crate::migrate`]): the envelope by
//!   [`format_chain`], renamed types through the registry's rename table,
//!   and each component and resource value through its type's steps
//!   (`"$version"`). A file newer than [`SCENE_VERSION`], or a value newer
//!   than its type, is refused. Loading never writes the file; `box
//!   upgrade` or the editor's Upgrade does, after a backup.

